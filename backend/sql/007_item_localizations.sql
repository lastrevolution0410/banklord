-- Version- and locale-specific, untrusted display metadata; stock ledger unaffected.
CREATE TABLE item_client_metadata (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  guild_id BIGINT UNSIGNED NOT NULL,
  client_flavor VARCHAR(32) NOT NULL,
  client_version VARCHAR(32) NOT NULL,
  client_build INT UNSIGNED NOT NULL,
  locale VARCHAR(8) NOT NULL,
  wow_item_id INT UNSIGNED NOT NULL,
  variant_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  variant_key VARCHAR(180) NOT NULL,
  localized_name VARCHAR(200) NOT NULL,
  quality TINYINT UNSIGNED NULL,
  item_level INT UNSIGNED NULL,
  required_level INT UNSIGNED NULL,
  item_type VARCHAR(100) NULL,
  item_sub_type VARCHAR(100) NULL,
  equip_loc VARCHAR(50) NULL,
  class_id INT UNSIGNED NULL,
  subclass_id INT UNSIGNED NULL,
  icon_file_id INT UNSIGNED NULL,
  icon_name VARCHAR(80) NULL,
  completeness ENUM('basic','tooltip') NOT NULL DEFAULT 'basic',
  stats_json TEXT NULL,
  tooltip_json MEDIUMTEXT NULL,
  captured_at DATETIME NOT NULL,
  imported_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_client_item (guild_id,client_flavor,client_version,client_build,locale,variant_hash),
  KEY idx_locale_variant (guild_id,locale,variant_hash),
  CONSTRAINT fk_client_metadata_guild FOREIGN KEY (guild_id) REFERENCES guilds(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
